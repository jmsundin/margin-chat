// Bundles the main-process parts of packages/vault-sync into one plain ESM file
// Electron can load without a TypeScript step: desktop/vault-sync.bundle.mjs.
// Runs before `start`, `dev` and every `dist:*` (desktop/package.json).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));

await build({
  entryPoints: [fileURLToPath(new URL("../packages/vault-sync/node.ts", import.meta.url))],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  outfile: `${here}vault-sync.bundle.mjs`,
  logLevel: "warning",
  banner: { js: "// Generated by desktop/build.mjs from packages/vault-sync. Do not edit." },
});
