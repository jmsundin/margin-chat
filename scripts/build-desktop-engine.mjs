// Bundles the desktop app's sync engine (desktop/sync/engine.ts, which runs the page's own vault sync code)
// into one Node module, desktop/vaultSyncEngine.mjs, because the app ships without node_modules.
// Run with Bun: `bun scripts/build-desktop-engine.mjs` (also part of `bun run desktop:engine`).
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const result = await Bun.build({
  entrypoints: [`${root}desktop/sync/engine.ts`],
  target: "node",
  format: "esm",
  minify: false,
  // Electron provides these; nothing else is left outside the bundle.
  external: ["electron"],
  naming: "vaultSyncEngine.mjs",
  outdir: `${root}desktop`,
  banner: "// Generated by scripts/build-desktop-engine.mjs from desktop/sync/engine.ts. Do not edit.",
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const [output] = result.outputs;
console.log(`Built ${output.path} (${Math.round(output.size / 1024)} KB)`);
