// Bundles Margin Chat's server for the desktop app's local mode (docs/desktop-local-mode.md) into
// desktop/local-server/, because the app ships without node_modules. Beside the bundle go the files
// it reads at run time: the database migrations and PGlite's Postgres build.
// Run with Bun: `bun scripts/build-desktop-server.mjs` (also part of `bun run desktop:engine`).
import { cp, mkdir, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const outdir = path.join(root, "desktop", "local-server");
await rm(outdir, { recursive: true, force: true });
const result = await Bun.build({
  entrypoints: [path.join(root, "server/local/server.mjs")],
  target: "node",
  format: "esm",
  minify: false,
  // One file: PGlite and every server module are inlined, so its asset URLs resolve beside it.
  splitting: false,
  external: ["electron"],
  naming: "server.mjs",
  outdir,
  banner: "// Generated by scripts/build-desktop-server.mjs from server/local/server.mjs. Do not edit.",
});
if (!result.success) {
  for (const message of result.logs) console.error(message);
  process.exit(1);
}
const require = createRequire(path.join(root, "package.json"));
const pgliteDist = path.dirname(require.resolve("@electric-sql/pglite"));
const vectorDist = path.dirname(require.resolve("@electric-sql/pglite-pgvector"));
await mkdir(outdir, { recursive: true });
for (const file of ["pglite.wasm", "pglite.data", "initdb.wasm"]) await cp(path.join(pgliteDist, file), path.join(outdir, file));
await cp(path.join(vectorDist, "vector.tar.gz"), path.join(outdir, "vector.tar.gz"));
await cp(path.join(root, "server/db/migrations"), path.join(outdir, "migrations"), { recursive: true });
const [output] = result.outputs;
console.log(`Built ${output.path} (${Math.round(output.size / 1024)} KB) with PGlite and migrations`);
