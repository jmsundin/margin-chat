import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const result = await Bun.build({
  entrypoints: [`${root}client/src/lib/workspaceMarkdown.ts`],
  target: "node",
  format: "esm",
  minify: false,
  outdir: `${root}server/vault`,
  naming: "codec.generated.mjs",
  banner: "// Generated by bun scripts/build-vault-codec.mjs. Edit client/src/lib/workspaceMarkdown.ts instead.",
});

if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exitCode = 1;
}
